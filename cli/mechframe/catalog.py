"""`mechframe catalog`: `catalog.json` from every built module's manifest (SPEC.md section 17).

An agent reads the whole library in this one small file. It holds only what
picking needs, in id order, with no timestamp, so it changes only when a
manifest does. Scaffolds (`modules/_<id>/`) and `planned` modules are left out.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from mechframe import __version__
from mechframe.source import ROOT, kernel_manifest, load_json, module_dirs

NAME = "catalog.json"
FIELDS = (
    "id",
    "name",
    "version",
    "status",
    "category",
    "summary",
    "use_when",
    "avoid_when",
    "requires",
    "conflicts",
)
COMMENT = (
    "Generated by `mechframe catalog` from every built module's module.json "
    "(SPEC.md section 17). Don't edit by hand."
)


def build(root: Path = ROOT) -> dict[str, Any]:
    entries = []
    for folder in module_dirs(root):
        manifest = load_json(folder / "module.json")
        if manifest["status"] == "planned":
            continue
        entries.append({field: manifest[field] for field in FIELDS})
    return {
        "$comment": COMMENT,
        "mechframe": __version__,
        "spec": kernel_manifest(root)["spec"],
        "generated_at": None,
        "modules": sorted(entries, key=lambda entry: str(entry["id"])),
    }


def render(data: dict[str, Any]) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def stale(root: Path = ROOT) -> bool:
    path = root / NAME
    if not path.is_file():
        return True
    return path.read_text("utf-8").replace("\r\n", "\n") != render(build(root))


def write(root: Path = ROOT) -> Path:
    path = root / NAME
    path.write_text(render(build(root)), encoding="utf-8", newline="\n")
    return path
