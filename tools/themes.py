ALIAS = re.compile(r"^\{([^{}]+)\}$")
REF = re.compile(r"\{([^{}]+)\}")
#: CSS's generic families are keywords: quoted, 'ui-monospace' would name a font.
GENERIC_FONTS = frozenset(
    {
        "serif",
        "sans-serif",
        "monospace",
        "cursive",
        "fantasy",
        "system-ui",
        "ui-serif",
        "ui-sans-serif",
        "ui-monospace",
        "ui-rounded",
        "math",
        "emoji",
        "fangsong",
    }
)
HEADER = "/* Generated by `python -m tools.themes` from tokens.json. Don't edit by hand. */\n"
REDUCED = "mf.reducedMotion"


@dataclass(frozen=True)
class Token:
    path: tuple[str, ...]
    value: Any
    type: str | None
    extensions: dict[str, Any] = field(default_factory=dict, compare=False, hash=False)

    @property
    def dotted(self) -> str:
        return ".".join(self.path)

    @property
    def var(self) -> str:
        return PREFIX + "-".join(
            re.sub(r"(?<!^)(?=[A-Z])", "-", part).lower() for part in self.path
        )


@dataclass(frozen=True)
class Theme:
    """One theme: its name (its folder's) and its tokens, in file order."""

    folder: Path
    tokens: list[Token]

    @property
    def name(self) -> str:
        return self.folder.name

    @property
    def by_path(self) -> dict[str, Token]:
        return index(self.tokens)


def flatten(
    node: dict[str, Any], path: tuple[str, ...] = (), inherited: str | None = None
) -> list[Token]:
    kind = node.get("$type", inherited)
    out: list[Token] = []
    for key, child in node.items():
        if key.startswith("$"):
            continue
        if isinstance(child, dict) and "$value" in child:
            extensions = child.get("$extensions") or {}
            out.append(Token((*path, key), child["$value"], child.get("$type", kind), extensions))
        elif isinstance(child, dict):
            out.extend(flatten(child, (*path, key), kind))
    return out


def index(tokens: list[Token]) -> dict[str, Token]:
    return {token.dotted: token for token in tokens}


def load(folder: Path) -> Theme:
    data = json.loads((folder / "tokens.json").read_text("utf-8"))
    return Theme(folder, flatten(data))


def discover(root: Path = THEMES) -> list[Theme]:
    """Every theme in `root`: each folder with a tokens.json, by name."""
    return [load(folder) for folder in sorted(root.iterdir()) if (folder / "tokens.json").is_file()]


def _number(value: Any) -> str:
    return f"{value:g}" if isinstance(value, float) else str(value)


def _fonts(value: list[str], quote: bool) -> str:
    return ", ".join(f if f in GENERIC_FONTS or not quote else f"'{f}'" for f in value)


def _resolve_refs(
    text: str, token: Token, by_path: dict[str, Token], seen: tuple[str, ...], to: str
) -> str:
    def sub(match: re.Match[str]) -> str:
        target = match.group(1)
        if target in seen or target == token.dotted or target not in by_path:
            raise ValueError(f"{token.dotted}: reference {{{target}}} is missing or circular")
        if to == "var":
            literal(by_path[target], by_path, (*seen, token.dotted))  # checks the chain
            return f"var({by_path[target].var})"
        return literal(by_path[target], by_path, (*seen, token.dotted))

    return REF.sub(sub, text)


def literal(token: Token, by_path: dict[str, Token], seen: tuple[str, ...] = ()) -> str:
    """The token as plain CSS, every reference replaced by its literal value."""
    value = token.value
    if isinstance(value, str):
        return _resolve_refs(value, token, by_path, seen, to="literal")
    if token.type == "typography" and isinstance(value, dict):
        return _shorthand(token, by_path, seen, to="literal")
    if token.type == "fontFamily" and isinstance(value, list):
        return _fonts(value, quote=False)
    if token.type == "cubicBezier" and isinstance(value, list):
        return "cubic-bezier(" + ", ".join(f"{x:g}" for x in value) + ")"
    return _number(value)


def _part(
    token: Token, value: Any, by_path: dict[str, Token], seen: tuple[str, ...], to: str
) -> str:
    if isinstance(value, str):
        return _resolve_refs(value, token, by_path, seen, to)
    if isinstance(value, list):
        return _fonts(value, quote=to == "var")
    return _number(value)


TYPOGRAPHY = ("fontFamily", "fontSize", "fontWeight", "lineHeight")


def _shorthand(token: Token, by_path: dict[str, Token], seen: tuple[str, ...], to: str) -> str:
    value = token.value
    missing = [key for key in TYPOGRAPHY if key not in value]
    if missing:
        raise ValueError(f"{token.dotted}: a typography token needs {', '.join(missing)}")
    family, size, weight, height = (
        _part(token, value[key], by_path, seen, to) for key in TYPOGRAPHY
    )
    return f"{weight} {size}/{height} {family}"


def css_value(token: Token, by_path: dict[str, Token]) -> str:
    """The token's value in CSS, references as var()."""
    value = token.value
    if isinstance(value, str):
        return _resolve_refs(value, token, by_path, (), to="var")
    if token.type == "typography" and isinstance(value, dict):
        return _shorthand(token, by_path, (), to="var")
    if token.type == "fontFamily" and isinstance(value, list):
        return _fonts(value, quote=True)
    if token.type == "cubicBezier" and isinstance(value, list):
        return "cubic-bezier(" + ", ".join(f"{x:g}" for x in value) + ")"
    return _number(value)


def declarations(token: Token, by_path: dict[str, Token]) -> list[tuple[str, str]]:
    """The CSS custom properties a token writes: one, or a type role's two."""
    found = [(token.var, css_value(token, by_path))]
    if token.type == "typography" and isinstance(token.value, dict):
        tracking = token.value.get("letterSpacing", "normal")
        found.append((f"{token.var}-tracking", _part(token, tracking, by_path, (), to="var")))
    elif (
        token.type == "typography"
        and isinstance(token.value, str)
        and (match := ALIAS.match(token.value))
    ):
        # An alias of another type role takes its tracking too (CodeRabbit on #80).
        found.append((f"{token.var}-tracking", f"var({by_path[match.group(1)].var}-tracking)"))
    return found


def render_css(theme: Theme) -> str:
    by_path = theme.by_path
    lines = [HEADER, f'[data-theme="{theme.name}"] {{\n']
    for token in theme.tokens:
        lines += [f"  {name}: {value};\n" for name, value in declarations(token, by_path)]
    lines.append("}\n\n@media (prefers-reduced-motion: reduce) {\n")
    lines.append(f'  [data-theme="{theme.name}"] {{\n')
    for token in theme.tokens:
        if token.type == "duration":
            lines.append(f"    {token.var}: 0s;\n")
        elif REDUCED in token.extensions:
            lines.append(f"    {token.var}: {token.extensions[REDUCED]};\n")
    lines.append("  }\n}\n")
    return "".join(lines)


def _tailwind_name(token: Token) -> str | None:
    """Tailwind v4's theme variable for a token, or None for one it has no namespace for."""
    path = token.path
    head = path[0]
    if head == "color":
        if len(path) == 2:
            return f"--color-{path[1]}"  # bg-surface: the roles, not the palette
        if path[1] == "alpha" and len(path) == 4:
            return f"--color-{path[2]}-{path[3]}"  # bg-bone-5
        if path[1] == "brand" and len(path) == 3:
            return f"--color-brand-{path[2]}"
        return None
    rules = {
        ("font",): "--font-{last}",
        ("typography", "fontFamily"): "--font-{last}",
        ("typography", "size"): "--text-{last}",
        ("typography", "fluid"): "--text-{last}",
        ("typography", "scale"): "--text-{last}",
        ("typography", "fontWeight"): "--font-weight-{last}",
        ("typography", "lineHeight"): "--leading-{last}",
        ("typography", "letterSpacing"): "--tracking-{last}",
        ("radius",): "--radius-{last}",
        ("shadow",): "--shadow-{last}",
        ("motion", "easing"): "--ease-{last}",
    }
    for prefix, name in rules.items():
        if path[: len(prefix)] == prefix and len(path) == len(prefix) + 1:
            return name.format(last=path[-1])
    return None


def render_tailwind(theme: Theme) -> str:
    lines = [HEADER, '@import "tailwindcss";\n@import "./tokens.css";\n\n@theme inline {\n']
    seen: set[str] = set()
    for token in theme.tokens:
        name = _tailwind_name(token)
        if name and name not in seen:  # a kernel alias and a ramp can name one variable
            seen.add(name)
            lines.append(f"  {name}: var({token.var});\n")
    by_path = theme.by_path
    # Tailwind's spacing is a multiple of --spacing; space.<n> is n of them (p-2.5 is 10px).
    if "space.1" in by_path:
        lines.append(f"  --spacing: var({by_path['space.1'].var});\n")
    if "layout.container" in by_path:
        lines.append(f"  --container-page: var({by_path['layout.container'].var});\n")
    lines.append("}\n")
    return "".join(lines)


def outputs(theme: Theme) -> dict[Path, str]:
    return {
        theme.folder / "tokens.css": render_css(theme),
        theme.folder / "tailwind.css": render_tailwind(theme),
    }


def main(argv: list[str] | None = None, root: Path = THEMES) -> int:
    argv = sys.argv[1:] if argv is None else argv
    check = "--check" in argv
    stale = []
    for theme in discover(root):
        for target, text in outputs(theme).items():
            if check:
                if not target.is_file() or target.read_bytes().decode("utf-8") != text:
                    stale.append(target)
            else:
                target.write_bytes(text.encode("utf-8"))
                print(f"Wrote {target.relative_to(root.parent)}")
    if stale:
        print("stale: " + ", ".join(str(path.relative_to(root.parent)) for path in stale))
        print("Run python -m tools.themes.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
