"""Build each theme's CSS from its tokens (K4 contract §2; themes/README.md).

    python -m tools.themes           write every theme's tokens.css and tailwind.css
    python -m tools.themes --check   exit 1 if any is out of date

A theme is a folder in themes/ with a `tokens.json` in W3C design-tokens
format. Every token becomes `--mf-<path>` in kebab case: `color.text-strong`
is `--mf-color-text-strong`, `typography.fontFamily.display`
`--mf-typography-font-family-display`. An alias such as
`{color.palette.bone}` becomes `var(--mf-color-palette-bone)`, and so does
each reference inside a longer value (a shadow, a filter). A typography
token (`type.page-title`) becomes a `font` shorthand and its tracking:
`--mf-type-page-title` and `--mf-type-page-title-tracking`.

The tokens sit on `[data-theme="<name>"]` alone: a site names its theme on
`<html data-theme="...">`. Under `prefers-reduced-motion` every duration is
0s, and a token whose `$extensions` gives `mf.reducedMotion` takes that
value (a looping effect's play state, `paused`).

`REQUIRED` is the kernel's own tokens, which every theme defines and the
kit styles itself with; themes/README.md lists them with their meaning,
and tests/test_themes.py holds the two lists equal. Ported from the
Vibrant Mindz theme's `build_tokens.py` (VM Website, design/theme).
"""

